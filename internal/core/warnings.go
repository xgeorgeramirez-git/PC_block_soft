package core

// WarnThresholds — пороги предупреждений R9 в минутах, по убыванию (D-54).
var WarnThresholds = [4]int{30, 15, 5, 1}

// warnings — пороги как события, а не таймер (Ruling 10, L-06, L-118): порог T взводится,
// только если при взведении до ближайшего события строго больше T·60 с (R9, D-54: вход ровно
// за 30 мин или «+30» при нуле не дают «за 30»); срабатывает один раз, когда дельта стала
// T·60 с или меньше. Взводятся заново при сдвиге события (доп. время, бонус, пауза, новые
// правила, новые сутки); прошедшие пороги при этом не взводятся: при входе за 3 мин до события
// покажется только порог 1 мин. Ещё не сработавший порог при пересчёте остаётся взведённым,
// пока дельта не меньше T·60 с, а сработавший взводится снова только по строгому правилу:
// пересчёт без сдвига события (сохранение тех же правил в ту же секунду) не даёт повтора.
// Хранит вид ближайшего события (R9: текст зависит от того, что кончится: лимит, интервал, пауза).
type warnings struct {
	armed [len(WarnThresholds)]bool
	event WarnEvent
}

// arm взводит пороги для дельты deltaS секунд до ближайшего события вида ev; limited =
// false (без события — без лимита, безопасный режим) гасит все пороги.
func (w *warnings) arm(deltaS int, ev WarnEvent, limited bool) {
	w.event = ev
	for i, t := range WarnThresholds {
		keep := w.armed[i] && deltaS >= t*60 // взведён и ещё не сработал: граница не потеряна
		w.armed[i] = limited && (deltaS > t*60 || keep)
	}
}

// fire гасит сработавшие при дельте deltaS пороги и возвращает меньший из них (одна
// причина — одно уведомление) и вид события; 0 — ничего не сработало.
func (w *warnings) fire(deltaS int) (int, WarnEvent) {
	got := 0
	for i, t := range WarnThresholds {
		if w.armed[i] && deltaS <= t*60 {
			w.armed[i] = false
			got = t
		}
	}
	if got == 0 {
		return 0, WarnNone
	}
	return got, w.event
}
