// Package systray — значок у часов и мини-панель: надпись остатка, подсказка, цвет статуса,
// картинка значка и окно по щелчку.
//
// Файлы без тега windows (на стандартной библиотеке, ядре и ipc) решают, что показать:
// надпись (FR-7), подсказку (ТЗ 8.2.1), цвет статуса (ТЗ 8.0 п.3 и 9), значок 16, 24 и 32
// пикселя своим растровым шрифтом и ICO (format.go, icon.go, ico.go), вид значка по ответу
// службы и устаревание цифр (view.go), вид мини-панели взрослого сеанса и её место у значка
// (panel.go), табло остатка детского сеанса (D-53): что показать (countdown.go), где что лежит
// (card_layout.go) и рисунок со сглаженными углами, переходом цвета и тенями (card_render.go).
// Окно сообщений, Shell_NotifyIconW, мини-панель и табло Win32 живут в файлах *_windows.go и
// только рисуют готовое, поэтому всё, что решается, проверяется тестами на Linux.
//
// Run (run_windows.go) работает в сеансе пользователя: раз в PollEvery (раз в секунду, пока
// открыто табло) спрашивает службу (GetChildStatus), обновляет значок, по щелчку открывает
// табло (ребёнку) или мини-панель (взрослому), а стрелка табло и кнопки панели просят службу
// открыть окно (OpenWindow, Ruling 19). Нажатия клавиш не читаются и не пишутся (R23).
