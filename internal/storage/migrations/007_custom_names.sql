-- Назначение: фидбек-раунд 0.3.1 (FB-11, D-59): свои названия программ.
-- Правки схемы идут новой миграцией, 001–006 не переписываются (L-131).

-- programs.custom_name: своё название, которое дал родитель (1–60 символов); '' — название из файла
-- (display_name). Название из файла не затирается: пустое своё снова показывает его, снимок программ
-- своё название не трогает. Как называть программу, решает programs.DisplayName.
ALTER TABLE programs ADD COLUMN custom_name TEXT NOT NULL DEFAULT '' CHECK (length(custom_name) <= 60);
