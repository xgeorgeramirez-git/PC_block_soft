// Package ipc — канал связи службы программы с её окнами, стражем сеанса и значком на том
// же компьютере: именованный канал Windows, без сети (NFR-1: пакет net не используется).
//
// # Что где лежит
//
//   - protocol.go, payload.go, peer.go, commands.go, status.go: протокол, типы команд и ответов,
//     ChildStatus. Только стандартная библиотека и internal/core, тесты идут на любой системе.
//   - server_windows.go, client_windows.go, pipe_windows.go, identity_windows.go: транспорт
//     (golang.org/x/sys/windows). Проверяется в CI: кросс-vet в ci.yml, тесты канала
//     (pipe_windows_test.go) в windows.yml.
//
// # Кадр
//
// Кадр состоит из 4 байт длины тела (little-endian, без знака) и тела в JSON. Длина 0 или
// больше MaxFrame (1 МБ) — ошибка, память под тело выделяется только после проверки длины.
// Запрос — Msg{cmd, token, payload}, ответ — Reply{ok, error, field, payload}; ключи JSON в
// нижнем верблюжьем регистре, длительности в секундах (…S), моменты в UTC мс (…Ms).
// Reply.Error — готовый текст для человека без технических деталей (L-112), Reply.Field —
// поле формы, к которому он относится (L-121). Decode и ReadFrame не паникуют на любом мусоре
// (FuzzDecode).
//
// Массивы в ответах — всегда «[]», не null (L-22): OK и Payload заменяют nil-срезы пустыми
// на любой глубине. Чтобы окно и служба не разошлись в типах, testdata/contract.json хранит
// пример запроса и ответа каждой команды; контракт-тест сверяет файл с Go-типами, vitest
// разбирает те же примеры в frontend/src/api.ts. Обновить после изменения типов:
//
//	go test ./internal/ipc/ -run Contract -update
//
// Каждая команда из AllCommands обязана иметь пример в контракте и строку в таблице прав
// службы (internal/service): новая команда без того и другого не пройдёт тесты.
//
// # Безопасность (Ruling 17, NFR-9)
//
// Канал создаётся с дескриптором, где полный доступ только у системы и администраторов, а у
// интерактивных пользователей нет права создать свой экземпляр канала; первый экземпляр
// создаётся с FILE_FLAG_FIRST_PIPE_INSTANCE, поэтому занять имя раньше службы нельзя.
// Удалённые клиенты отклоняются. Serve определяет личность клиента (Peer: PID, сеанс, SID,
// повышение, группа Администраторов, система) после первого кадра и передаёт её обработчику
// с каждым запросом. Права на команды канал не проверяет: это делает служба по Peer и
// токену родительской сессии (R19).
//
// Клиент открывает канал с уровнем SECURITY_IDENTIFICATION: служба узнаёт, кто он, но не может
// действовать от его имени. До отправки любых данных (тем более пароля) Dial проверяет, что
// канал держит процесс системы: владелец токена S-1-5-18; если токен чужого процесса
// обычному пользователю недоступен, то процесс канала должен совпасть с PID службы PCBlock
// по данным менеджера служб. Иначе ошибка ErrNotService с текстом «Программа не отвечает».
//
// # Сроки и остановка (L-57)
//
// Блокирующие ConnectNamedPipe, ReadFile и WriteFile нельзя прервать, а они вешают остановку
// службы, поэтому весь ввод-вывод идёт с перекрытием, а остановка по контексту и сроки
// отменяют его через CancelIoEx. У клиента есть срок подключения (Dial) и срок на запрос и
// ответ; сервер отпускает молчащее соединение через пять минут, недосланное тело кадра через
// десять секунд, а обслуживает не больше 64 соединений сразу. Serve при отмене контекста
// возвращается за доли секунды.
//
// Клиент держит одно соединение. Если служба его закрыла (простой, перезапуск), записанный
// запрос до неё не дошёл, и Do один раз повторяет его на новом соединении. После обрыва на
// чтении запрос не повторяется: служба могла его выполнить.
