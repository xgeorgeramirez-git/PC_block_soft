// Package service — служба PCBlock: фоновая часть, которая считает время за компьютером,
// отвечает на команды окон и стража и по правилам ТЗ просит показать экранные части
// (страж сеанса, значок у часов, окна). Ставит и удаляет её администратор, в любой момент
// он может остановить службу или удалить программу (ТЗ 3.2, NFR-10).
//
// # Что где лежит
//
// Логика службы написана на портах и стандартной библиотеке, поэтому её тесты идут на любой
// системе без Windows, SQLite и Wails (ТЗ 3.3):
//
//   - ports.go: порты (хранилище, хеш пароля, запуск процессов в сеансах, проверка прав
//     учётки, список учёток, политика Диспетчера задач, журнал);
//   - service.go, loop.go: Service держит по одному core.Engine на ребёнка; Tick раз в
//     секунду часов ядра, Housekeep раз в реальную секунду, Shutdown при остановке;
//   - sessions.go: страж и значок в каждом сеансе, окна по просьбе, слежение за процессами
//     (FR-27, R17в), защита от обхода и память о запущенных процессах (procs.json);
//   - commands.go, handlers.go, parent.go: Handle разбирает команды канала связи, таблица
//     прав на каждую команду из ipc.AllCommands, родительская сессия R19;
//   - testmode.go: значения тестового режима (ТЗ 10.8) и часы ядра по ним;
//   - openstore.go: открытие базы с безопасным режимом при порче (R18, NFR-8);
//   - rotatelog.go, procstate.go, windowclient.go: журнал работы по кругу, чтение и запись
//     памяти о запущенных процессах, клиентская сторона моста окна;
//   - journaltext.go, texts.go: журнал простыми словами и тексты ответов.
//
// Всё, что зависит от golang.org/x/sys/windows, лежит в подпакете winhost (файлы *_windows.go:
// svc.Handler, установка службы, чтение тестового режима, сеансы и процессы, проверка R1,
// список учёток, политика Диспетчера задач, адаптеры хранилища и хеша пароля, служебные ключи
// приёмки). Подпакет проверяется в CI: кросс-vet в ci.yml, смоук на настоящей Windows в
// windows.yml. Оно вынесено из этого пакета, чтобы порог покрытия internal/service (85 %)
// мерился на логике, а не на Win32-вызовах, которые юнит-тестами не покрыть (серия R4 идёт на
// Windows и считает все файлы пакета, собираемые для неё).
//
// # Часы
//
// Учёт идёт по часам ядра (core.Clock): в тестовом режиме они ускорены, и служба тикает
// раз в секунду именно этих часов. Всё, что должно идти по настоящему времени (родительская
// сессия 10 мин, пауза после неверных паролей, окно «страж только что проверил пароль»,
// плашки, сроки реакции), считается по настоящим часам, которые передаёт вызывающий.
//
// # Решения
//
//   - Тик учёта идёт раз в секунду часов ядра, снимок датчиков стража старше 5 с (настоящих)
//     не засчитывается, ошибки записи в базу идут в журнал работы не чаще раза в минуту и
//     учёт не останавливают (R18).
//   - Страж и значок сами спрашивают службу, служба ничего не толкает: решение ядра лежит в
//     памяти, а ответ на GuardPoll (раз в секунду) и GetChildStatus несёт текущий статус,
//     новые предупреждения и команды стражу. Поэтому сохранённые родителем лимиты
//     действуют в ответе уже следующего опроса (FR-19).
//   - Пароль на экране блокировки проверяет служба по команде Login от стража. Страж не
//     хранит ни пароль, ни токен: служба помнит, что страж этого сеанса только что провёл
//     верную проверку (30 с, одно действие), и только в этом окне принимает «+15/+30/+60»,
//     «Снять блокировку» и «Открыть настройки» от него.
//   - Родительская сессия привязана к процессу окна (PID и момент создания процесса) и
//     заканчивается через 10 мин без действий, по Logout и по закрытию окна. Чтение
//     (GetToday, SessionState и подобное) сессию не продлевает, правки и ExtendSession
//     продлевают.
//   - Тестовые команды (TestGuard, TestClock, GuardState) служба принимает только в
//     тестовом режиме. GuardState работает в обе стороны: страж в тестовом режиме присылает
//     свой вид (кнопки, поля), проверяющий читает его пустым запросом.
